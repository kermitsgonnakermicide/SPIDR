# ── Render markdown body to PDF via a tiny converter ───────
def render_inline(pdf, text):
    """Render a line that may contain **bold**, `code`, [link](url)."""
    pat = re.compile(r"(\*\*([^*]+)\*\*|`([^`]+)`|\[([^\]]+)\]\(([^)]+)\)|(https?://\S+))")
    pos = 0
    while pos < len(text):
        m = pat.search(text, pos)
        if not m:
            pdf.set_text_color(0, 0, 0)
            pdf.set_font("Helvetica", "", 10)
            pdf.write(5, text[pos:])
            break
        before = text[pos:m.start()]
        if before:
            pdf.set_text_color(0, 0, 0)
            pdf.set_font("Helvetica", "", 10)
            pdf.write(5, before)
        if m.group(2):                       # **bold**
            pdf.set_font("Helvetica", "B", 10)
            pdf.write(5, m.group(2))
        elif m.group(3):                     # `code`
            pdf.set_font("Courier", "", 9)
            pdf.set_text_color(180, 40, 40)
            pdf.write(5, m.group(3))
        elif m.group(5):                     # [text](url)
            pdf.set_font("Helvetica", "U", 9)
            pdf.set_text_color(20, 80, 180)
            pdf.write(5, m.group(4))
        elif m.group(6):                     # bare URL
            pdf.set_font("Helvetica", "U", 8)
            pdf.set_text_color(20, 80, 180)
            pdf.write(5, m.group(6))
        pos = m.end()
        pdf.set_text_color(0, 0, 0)

def emit_para(pdf, text, indent=0):
    pdf.set_x(pdf.l_margin + indent)
    pdf.set_font("Helvetica", "", 10)
    render_inline(pdf, text)
    pdf.ln(6)

def emit_code(pdf, text):
    pdf.set_font("Courier", "", 8)
    pdf.set_text_color(40, 40, 40)
    pdf.set_x(pdf.l_margin)
    for raw in text.split("\n"):
        # Sanitize anything that breaks Helvetica/Courier encodings
        line = raw.replace("\t", "    ")
        try:
            pdf.cell(0, 4.2, line, new_x="LMARGIN", new_y="NEXT")
        except Exception:
            safe = line.encode("latin-1", "replace").decode("latin-1")
            pdf.cell(0, 4.2, safe, new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(3)

def emit_h(pdf, level, text):
    sizes = {1: 17, 2: 14, 3: 12}
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", sizes.get(level, 11))
    pdf.set_text_color(30, 60, 100)
    pdf.multi_cell(0, sizes.get(level, 11)*0.6, text)
    pdf.set_text_color(0, 0, 0)

# ── Iterate over markdown ─────────────────────────────────
in_code  = False
code_buf = []
in_table = False
list_indent = 0
for raw in md.split("\n"):
    line = raw.rstrip()
    if line.startswith("```"):
        if not in_code:
            in_code = True
            code_buf = []
        else:
            in_code = False
            emit_code(pdf, "\n".join(code_buf))
            code_buf = []
        continue
    if in_code:
        code_buf.append(raw)
        continue
    if not line.strip():
        pdf.ln(2)
        continue
    # Headings
    m = re.match(r"^(#{1,3})\s+(.*)$", line)
    if m:
        emit_h(pdf, len(m.group(1)), m.group(2).strip())
        continue
    # Bulleted / numbered / blockquote
    if line.startswith("> "):
        emit_para(pdf, line[2:], indent=4)
        continue
    m = re.match(r"^(\s*)[-*]\s+(.*)$", line)
    if m:
        emit_para(pdf, "* " + m.group(2), indent=4)
        continue
    m = re.match(r"^(\s*)(\d+)\.\s+(.*)$", line)
    if m:
        emit_para(pdf, m.group(2) + ". " + m.group(3), indent=4)
        continue
    # Tables: render `| col | col |` as comma-separated caption lines
    if line.startswith("|"):
        emit_para(pdf, line.replace("|", " | ").strip(" |"), indent=2)
        continue
    # Body paragraph
    emit_para(pdf, line)

pdf.output(str(OUT))
